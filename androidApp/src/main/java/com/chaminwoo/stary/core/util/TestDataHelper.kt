    suspend fun seed(
        userId: String = "test_user",
        userName: String = "테스트"
    ) {
        val repo = FirebaseDiaryRepository()
        val now = System.currentTimeMillis()

        places.forEachIndexed { i, place ->
            // 같은 장소 좌표에서 ±0.002° (~200m) 랜덤 분산 → 자연스러운 클러스터 형성
            val latOffset = (Random.nextDouble() - 0.5) * 0.004
            val lngOffset = (Random.nextDouble() - 0.5) * 0.004

            repo.saveDiary(
                Diary(
                    userId = userId,
                    userName = userName,
                    title = place.title,
                    content = place.content,
                    latitude = place.lat + latOffset,
                    longitude = place.lng + lngOffset,
                    createdAt = now - (i * 10_800_000L),
                    likeCount = Random.nextInt(5, 300),
                    commentCount = Random.nextInt(0, 50),
                    starType = Random.nextInt(0, 5),
                    starColor = Random.nextInt(0, 12)
                )
            )
        }
    }
